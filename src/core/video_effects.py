"""Registry for the short video-derived battle effects.

The source videos stay in ``tmp/effect-source``.  Runtime code only loads the
small, transparent PNG sequences generated by ``tools/extract_video_effects.py``.
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class VideoEffectSpec:
    key: str
    source_id: str
    label: str
    frame_count: int
    fps: float
    default_size: tuple[int, int]
    blend: str = "add"

    @property
    def duration(self) -> float:
        return self.frame_count / self.fps

    def frame_path(self, index: int) -> str:
        return f"graphic/effects/{self.key}/{self.key}_{index:02d}.png"


