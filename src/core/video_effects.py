VIDEO_EFFECTS: dict[str, VideoEffectSpec] = {spec.key: spec for spec in VIDEO_EFFECT_SPECS}


def video_effect_spec(key: str) -> VideoEffectSpec:
    try:
        return VIDEO_EFFECTS[key]
    except KeyError as exc:  # pragma: no cover - caller programming error
        raise ValueError(f"unknown video effect: {key!r}") from exc
